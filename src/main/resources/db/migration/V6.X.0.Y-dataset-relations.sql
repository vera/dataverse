CREATE TABLE IF NOT EXISTS datasetrelation (
                                              id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                                              dataset_id BIGINT NOT NULL,
                                              related_dataset_id BIGINT NOT NULL,
                                              relation_type VARCHAR(255) NOT NULL,
                                              definition_point_id BIGINT NOT NULL,
                                              CHECK (dataset_id < related_dataset_id),
                                              UNIQUE (dataset_id, related_dataset_id, relation_type),
                                              CONSTRAINT fk_datasetrelations_dataset_not_equal_related_dataset check (dataset_id <> related_dataset_id),
                                              CONSTRAINT fk_datasetrelations_dataset FOREIGN KEY (dataset_id) REFERENCES dvobject(id),
                                              CONSTRAINT fk_datasetrelations_related_dataset FOREIGN KEY (related_dataset_id) REFERENCES dvobject(id)
);

CREATE INDEX IF NOT EXISTS index_datasetrelation_dataset ON datasetrelation (dataset_id);
CREATE INDEX IF NOT EXISTS index_datasetrelation_related_dataset ON datasetrelation (related_dataset_id);